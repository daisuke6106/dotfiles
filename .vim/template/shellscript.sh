#!/bin/bash
####################################################################################################
# title
# 
# detail
####################################################################################################
# ==================================================================================================
# Useage
# ==================================================================================================
_usage() {
    echo "usage:"
    echo "${0} -a|--aaa AAA [-b|--bbb BBB] [-c|--ccc]"
    exit 1
}

# ==================================================================================================
# 環境設定
# ==================================================================================================
# --------------------------------------------------------------------------------------------------
# 自身のシェルが存在するディレクトリ
# --------------------------------------------------------------------------------------------------
# 相対パス
OWN_DIR_RELATIVE_PATH=$(dirname $0)
# 絶対パス
OWN_DIR_ABSOLUTE_PATH=$(cd ${OWN_DIR_RELATIVE_PATH} && pwd)
cd -

# 共通の環境設定
source $(dirname $0)/env.sh

# ==================================================================================================
# 引数取得
# ==================================================================================================
while [ $# -gt 0 ];
do
    case "$1" in
        # ------------------------------------------------------------------------------------------
        # パラメタの抽出（長形式・短形式の両方を許容）
        # ------------------------------------------------------------------------------------------
        -a|--aaa)  AAA="$2"; shift 2 ;;
        -b|--bbb)  BBB="$2"; shift 2 ;;

        # ------------------------------------------------------------------------------------------
        # パラメタを受け取らないスイッチの抽出（値を消費しないため shift は1つ分だけ）
        # ------------------------------------------------------------------------------------------
        -c|--ccc)  CCC="true"; shift ;;

        # ------------------------------------------------------------------------------------------
        # 未定義オプションが指定された場合は _usage を実行する
        # ------------------------------------------------------------------------------------------
        # "-"で始まるが、上記のどのオプションにも一致しなかった場合（未定義オプション）
        -*)        _usage ;;
        # "-"で始まらない引数（オプションの値ではない余分な位置引数）は読み捨てる
        *)         shift ;;
    esac
done

# ==================================================================================================
# 必須チェック
# ==================================================================================================
[[ "${AAA}" == "" ]] && _usage
# [[ "${BBB}" == "" ]] && _usage # 任意項目のため必須チェックから除外

# ==================================================================================================
# 日時算出
# ==================================================================================================
# NOW_YYYYMMDDHHMMSS=$(date '+%Y/%m/%d %H:%M:%S')
# NOW_YYYYMMDD=$(date '+%Y/%m/%d')
# NOW_HHMMSS=$(date '+%H:%M:%S')

# ==================================================================================================
# メイン処理
# ==================================================================================================
# --------------------------------------------------------------------------------------------------
# ifテンプレ
# --------------------------------------------------------------------------------------------------
if   [ "" = "" ]; then
    echo "if";
elif [ "" = "" ]; then
    echo "elif";
else
    echo "else";
fi

# --------------------------------------------------------------------------------------------------
# コマンド正常終了判定テンプレ
# --------------------------------------------------------------------------------------------------
if cp from to; then
  echo "コピーに成功しました"
else
  echo "コピーに失敗しました"
fi

# 失敗したときだけ処理を行う場合
# （補足: POSIXで標準化されているが、Bourneシェルは非対応）
if ! cp from to; then
  echo "コピーに失敗しました"
fi

# ==================================================================================================
# 後処理
# ==================================================================================================
exit 0
