#!/bin/bash
# ==================================================================================================
# Useage
# ==================================================================================================
_usage() {
    echo "[概要] title" >&2
    echo "[詳細] detail" >&2
    echo "" >&2
    echo "usage:" >&2
    echo "${0} -a|--aaa AAA [-b|--bbb BBB] [-c|--ccc] [-d|--date DATE(YYYY-MM-DD,YYYY/MM/DD,YYYYMMDD)]" >&2
    exit 1
}

# ==================================================================================================
# 環境設定
# ==================================================================================================
# --------------------------------------------------------------------------------------------------
# 自身のシェルが存在するディレクトリ
# --------------------------------------------------------------------------------------------------
# 相対パス
OWN_DIR_RELATIVE_PATH=$(dirname $0)
# 絶対パス
OWN_DIR_ABSOLUTE_PATH=$(cd ${OWN_DIR_RELATIVE_PATH} && pwd)

# --------------------------------------------------------------------------------------------------
# 共通の環境設定読み込み
# --------------------------------------------------------------------------------------------------
source ${OWN_DIR_RELATIVE_PATH}/env.sh

# ==================================================================================================
# 引数取得
# ==================================================================================================
while [ $# -gt 0 ];
do
    case "$1" in
        # ------------------------------------------------------------------------------------------
        # パラメタの抽出（長形式・短形式の両方を許容）
        # ------------------------------------------------------------------------------------------
        -a|--aaa)  AAA="$2"  ; shift 2 ;;
        -b|--bbb)  BBB="$2"  ; shift 2 ;;
        # パラメタを受け取らないスイッチの抽出（値を消費しないため shift は1つ分だけ）
        -c|--ccc)  CCC="true"; shift   ;;
        -d|--date) DATE="$2" ; shift 2 ;;

        # ------------------------------------------------------------------------------------------
        # 未定義オプションが指定された場合は _usage を実行する
        # ------------------------------------------------------------------------------------------
        # "-"で始まるが、上記のどのオプションにも一致しなかった場合（未定義オプション）
        -*)        _usage ;;
        # "-"で始まらない引数（オプションの値ではない余分な位置引数）は読み捨てる
        *)         shift ;;
    esac
done

# ==================================================================================================
# 関数定義
# ==================================================================================================
# --------------------------------------------------------------------------------------------------
# [概要] 日付チェック関数
# [詳細] 日付文字列が有効な日付かどうかをチェックする。
#        許容フォーマット:
#        - YYYYMMDD
#        - YYYY/MM/DD
#        - YYYY-MM-DD
# [種類] 関数
# [必須] 必須
# --------------------------------------------------------------------------------------------------
is_valid_date() {
    local input="$1"
    local year month day

    # フォーマットチェック & 分解
    if [[ "$input" =~ ^([0-9]{4})([0-9]{2})([0-9]{2})$ ]]; then
        # YYYYMMDD
        year="${BASH_REMATCH[1]}"
        month="${BASH_REMATCH[2]}"
        day="${BASH_REMATCH[3]}"
    elif [[ "$input" =~ ^([0-9]{4})/([0-9]{2})/([0-9]{2})$ ]]; then
        # YYYY/MM/DD
        year="${BASH_REMATCH[1]}"
        month="${BASH_REMATCH[2]}"
        day="${BASH_REMATCH[3]}"
    elif [[ "$input" =~ ^([0-9]{4})-([0-9]{2})-([0-9]{2})$ ]]; then
        # YYYY-MM-DD
        year="${BASH_REMATCH[1]}"
        month="${BASH_REMATCH[2]}"
        day="${BASH_REMATCH[3]}"
    else
        # どのフォーマットにも一致しない
        return 1
    fi

    # 10進数として扱うため先頭ゼロを除去(08 などが8進数扱いされるのを防ぐ)
    year=$((10#$year))
    month=$((10#$month))
    day=$((10#$day))

    # 月の範囲チェック
    if (( month < 1 || month > 12 )); then
        return 1
    fi

    # 各月の最大日数
    local days_in_month=(31 28 31 30 31 30 31 31 30 31 30 31)

    # 閏年判定(4で割り切れる かつ (100で割り切れない or 400で割り切れる))
    if (( (year % 4 == 0 && year % 100 != 0) || (year % 400 == 0) )); then
        days_in_month[1]=29
    fi

    # 日の範囲チェック
    if (( day < 1 || day > days_in_month[month-1] )); then
        return 1
    fi

    return 0
}
# --------------------------------------------------------------------------------------------------
# [概要] ログ出力用文字列生成
# [詳細] ログ出力するための文字列を生成し、標準出力に出力する。
# [種類] 関数
# [必須] 必須
# --------------------------------------------------------------------------------------------------
generate_log_string() {
    local log_level="$1"
    local message="$2"
    local timestamp
    timestamp=$(date '+%Y-%m-%d %H:%M:%S')
    echo "[$timestamp] [$log_level] $message"
}

# ==================================================================================================
# 必須チェック
# ==================================================================================================
[[ "${AAA}" == "" ]] && _usage
# [[ "${BBB}" == "" ]] && _usage # 任意項目のため必須チェックから除外

# ==================================================================================================
# 入力値チェック
# ==================================================================================================
# 日付チェック
if ! is_valid_date "${DATE}"; then
    echo "ERROR: 日付の形式が不正です。data=${DATE}" >&2
    exit 1
fi

# ==================================================================================================
# 変換処理
# ==================================================================================================
# 日付フォーマットを YYYY-MM-DD に統一
DATE=$(date -d "${DATE}" "+%Y-%m-%d")

# ==================================================================================================
# 日時算出
# ==================================================================================================
# NOW_YYYYMMDDHHMMSS=$(date '+%Y/%m/%d %H:%M:%S')
# NOW_YYYYMMDD=$(date '+%Y/%m/%d')
# NOW_HHMMSS=$(date '+%H:%M:%S')

# ==================================================================================================
# メイン処理
# ==================================================================================================
# 開始を出力
# ※標準出力のみ
generate_log_string "INFO" "[START]XXXを開始"
# ※ログにも出力
# generate_log_string "INFO" "[START]XXXを開始" | tee -a ${LOG_FILEPATH}

# --------------------------------------------------------------------------------------------------
# ifテンプレ
# --------------------------------------------------------------------------------------------------
if   [ "" = "" ]; then
    echo "if";
elif [ "" = "" ]; then
    echo "elif";
else
    echo "else";
fi

# --------------------------------------------------------------------------------------------------
# コマンド正常終了判定テンプレ
# --------------------------------------------------------------------------------------------------
if cp from to; then
  echo "コピーに成功しました"
else
  echo "コピーに失敗しました"
fi

# 失敗したときだけ処理を行う場合
# （補足: POSIXで標準化されているが、Bourneシェルは非対応）
if ! cp from to; then
  echo "コピーに失敗しました"
fi

# ==================================================================================================
# 後処理
# ==================================================================================================
# 終了を出力
# ※標準出力のみ
generate_log_string "INFO" "[END]XXXを開始"
# ※ログにも出力
# generate_log_string "INFO" "[END]XXXを開始" | tee -a ${LOG_FILEPATH}

exit 0
