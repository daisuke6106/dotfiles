#!/bin/bash
####################################################################################################
# title
# 
# detail
####################################################################################################
# ==================================================================================================
# Useage
# ==================================================================================================
_usage() {
    echo "usage:"
    echo "${0} -a AAA [-b BBB]"
    exit 1
}

# ==================================================================================================
# 環境設定
# ==================================================================================================
# --------------------------------------------------------------------------------------------------
# 自身のシェルが存在するディレクトリ
# --------------------------------------------------------------------------------------------------
# 相対パス
OWN_DIR_RELATIVE_PATH=$(dirname $0)
# 絶対パス
OWN_DIR_ABSOLUTE_PATH=$(cd ${OWN_DIR_RELATIVE_PATH} && pwd)
cd -

# 共通の環境設定
source $(dirname $0)/env.sh

# ==================================================================================================
# 引数取得
# ==================================================================================================
while getopts "a:b:" OPT;
do
    case "${OPT}" in
        # ------------------------------------------------------------------------------------------
        # パラメタの抽出
        # ------------------------------------------------------------------------------------------
        a)         AAA="${OPTARG}" ;;
        b)         AAA="${OPTARG}" ;;

        # ------------------------------------------------------------------------------------------
        # パラメタの抽出
        # ------------------------------------------------------------------------------------------
        # 未定義オプションが指定された場合、${OPT}に?が入る。
        # 必要なオプション引数がないば合う、${OPT}に:が入る。
        # その場合は _usage を実行する
        :|\?) _usage;;
    esac
done

# ==================================================================================================
# 必須チェック
# ==================================================================================================
[[ "${AAA}" == "" ]] && _usage
# [[ "${BBB}" == "" ]] && _usage # 任意項目のため必須チェックから除外

# ==================================================================================================
# 日時算出
# ==================================================================================================
# NOW_YYYYMMDDHHMMSS=$(date '+%Y/%m/%d %H:%M:%S')
# NOW_YYYYMMDD=$(date '+%Y/%m/%d')
# NOW_HHMMSS=$(date '+%H:%M:%S')

# ==================================================================================================
# メイン処理
# ==================================================================================================
# --------------------------------------------------------------------------------------------------
# ifテンプレ
# --------------------------------------------------------------------------------------------------
if   [ "" = "" ]; then
    echo "if";
elif [ "" = "" ]; then
    echo "elif";
else
    echo "else";
fi

# --------------------------------------------------------------------------------------------------
# コマンド正常終了判定テンプレ
# --------------------------------------------------------------------------------------------------
if cp from to; then
  echo "コピーに成功しました"
else
  echo "コピーに失敗しました"
fi

# 失敗したときだけ処理を行う場合
# （補足: POSIXで標準化されているが、Bourneシェルは非対応）
if ! cp from to; then
  echo "コピーに失敗しました"
fi

# ==================================================================================================
# 後処理
# ==================================================================================================
exit 0
